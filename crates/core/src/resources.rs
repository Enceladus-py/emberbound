use bevy::prelude::*;
use emberbound_domain::bestiary::DragonKind;
use emberbound_domain::ports::RandomSource;
use emberbound_domain::progression::{Boon, HeroStats, Progress};
use emberbound_domain::world::{self, WorldMap};

/// Device-independent player input for this frame. Gameplay reads this, never
/// the keyboard: the app's input adapter fills it in `PreUpdate`.
#[derive(Resource, Debug, Clone, Copy, Default)]
pub struct PlayerIntent {
    /// Desired movement, length `0..=1`.
    pub movement: Vec2,
    /// Attack is held down.
    pub attack: bool,
    /// Dash was pressed this frame.
    pub dash: bool,
    /// Confirm / start was pressed this frame.
    pub confirm: bool,
    /// A numbered choice (0-based) was pressed this frame.
    pub choice: Option<usize>,
    /// A finger tapped here this frame, in logical window pixels from the
    /// top-left: a short touch that began and ended on the same menu
    /// (title, boon choice or end screen). Never set while fighting.
    pub tap: Option<Vec2>,
}

/// The hero's stats and progression for the current run.
/// Reset by the app on [`crate::RunSetup::Reset`]; boons are applied by the app.
#[derive(Resource, Debug, Clone, Copy, Default)]
pub struct HeroState {
    pub stats: HeroStats,
    pub progress: Progress,
}

/// Facts about the current run, for the HUD and end screens.
#[derive(Resource, Debug, Clone, Copy, Default)]
pub struct RunStats {
    /// Seconds spent fighting. Maintained by the app.
    pub elapsed: f32,
    /// Lesser monsters slain. Maintained by the app.
    pub kills: u32,
    /// Elder dragons slain. Maintained by the app.
    pub dragons_slain: u32,
    /// `0..=1` progress towards luring the next dragon. Maintained by `monsters`.
    pub lure_progress: f32,
    /// Next dragon to appear (or the one being fought). Maintained by `monsters`.
    pub next_dragon: Option<DragonKind>,
}

/// The boons currently on offer while in [`crate::RunPhase::ChoosingBoon`].
#[derive(Resource, Debug, Clone, Default)]
pub struct BoonOffer(pub Vec<Boon>);

/// The valley of the current run. Regenerated by the app on
/// [`crate::RunSetup::Reset`].
#[derive(Resource, Debug, Clone)]
pub struct Terrain(pub WorldMap);

impl Default for Terrain {
    fn default() -> Self {
        Self(world::generate(16, 16, &mut GameRng::new(1)))
    }
}

/// Add trauma (`0..=1`) to shake the camera; `world` applies and decays it.
#[derive(Resource, Debug, Clone, Copy, Default)]
pub struct ScreenShake {
    pub trauma: f32,
}

impl ScreenShake {
    pub fn add(&mut self, trauma: f32) {
        self.trauma = (self.trauma + trauma).clamp(0.0, 1.0);
    }
}

/// The game's random number generator: the adapter behind the domain's
/// [`RandomSource`] port (xorshift64*).
#[derive(Resource, Debug, Clone)]
pub struct GameRng(u64);

impl GameRng {
    pub fn new(seed: u64) -> Self {
        // Scramble the seed (splitmix64) so nearby seeds diverge; never zero.
        let mut z = seed.wrapping_add(0x9E37_79B9_7F4A_7C15);
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        Self((z ^ (z >> 31)).max(1))
    }

    /// Random unit vector.
    pub fn direction(&mut self) -> Vec2 {
        Vec2::from_angle(self.range(0.0, std::f32::consts::TAU))
    }
}

impl Default for GameRng {
    fn default() -> Self {
        Self::new(0xE4BE_7B07)
    }
}

impl RandomSource for GameRng {
    fn next_f32(&mut self) -> f32 {
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        let bits = self.0.wrapping_mul(0x2545_F491_4F6C_DD1D) >> 40;
        bits as f32 / (1u64 << 24) as f32
    }
}

pub(crate) fn register(app: &mut App) {
    app.init_resource::<PlayerIntent>()
        .init_resource::<HeroState>()
        .init_resource::<RunStats>()
        .init_resource::<BoonOffer>()
        .init_resource::<Terrain>()
        .init_resource::<ScreenShake>()
        .init_resource::<GameRng>();
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rng_is_uniform_enough_and_in_range() {
        let mut rng = GameRng::new(123);
        let samples: Vec<f32> = (0..10_000).map(|_| rng.next_f32()).collect();
        assert!(samples.iter().all(|v| (0.0..1.0).contains(v)));
        let mean = samples.iter().sum::<f32>() / samples.len() as f32;
        assert!((mean - 0.5).abs() < 0.02, "mean was {mean}");
    }
}
