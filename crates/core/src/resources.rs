/// Device-independent player input for this frame. Gameplay reads this, never
/// the keyboard: the app's input adapter fills it in `PreUpdate`.
#[derive(Resource, Debug, Clone, Copy, Default)]
pub struct PlayerIntent {
    /// Desired movement, length `0..=1`.
    pub movement: Vec2,
    /// Attack is held down.
    pub attack: bool,
    /// Dash was pressed this frame.
    pub dash: bool,
    /// Where the player is deliberately aiming the sword (unit vector), from
    /// the mouse while it is in use or a dragging sword finger. `None` leaves
    /// the aim to aim assist and facing.
    pub aim: Option<Vec2>,
    /// Confirm / start was pressed this frame.
    pub confirm: bool,
    /// Pause / resume was pressed this frame.
    pub pause: bool,
    /// Show / hide the minimap was pressed this frame.
    pub minimap: bool,
    /// A numbered choice (0-based) was pressed this frame.
    pub choice: Option<usize>,
    /// A finger tapped here this frame, in logical window pixels from the
    /// top-left: a short touch that began and ended on the same menu
    /// (title, pause, boon choice or end screen). Never set while fighting.
    pub tap: Option<Vec2>,
}

/// The hero's stats and progression for the current run.
/// Reset by the app on [`crate::RunSetup::Reset`]; boons are applied by the app.
#[derive(Resource, Debug, Clone, Copy, Default)]
pub struct HeroState {
    pub stats: HeroStats,
    pub progress: Progress,
}

/// Facts about the current run, for the HUD and end screens.
#[derive(Resource, Debug, Clone, Copy, Default)]
pub struct RunStats {
    /// Seconds spent fighting. Maintained by the app.
    pub elapsed: f32,
    /// Lesser monsters slain. Maintained by the app.
    pub kills: u32,
    /// Elder dragons slain. Maintained by the app.
    pub dragons_slain: u32,
    /// `0..=1` progress towards luring the next dragon. Maintained by `monsters`.
    pub lure_progress: f32,
    /// Next dragon to appear (or the one being fought). Maintained by `monsters`.
    pub next_dragon: Option<DragonKind>,
}

/// The best run so far, kept between runs (and page reloads). Loaded and
/// updated by the app when a run ends; read by `ui` for the end screens.
#[derive(Resource, Debug, Clone, Copy, Default)]
pub struct BestRunRecord {
    pub best: Option<BestRun>,
    /// The run that just ended set the record.
    pub new_best: bool,
}

/// The boons currently on offer while in [`crate::RunPhase::ChoosingBoon`].
#[derive(Resource, Debug, Clone, Default)]
pub struct BoonOffer(pub Vec<Boon>);

/// The ground of the current run: an endless world generated chunk by chunk
/// around the hero, or a finite valley (still used by tests). Regenerated by
/// the app on [`crate::RunSetup::Reset`].
///
/// Read it through [`Terrain::tiles`]; on the endless world only chunks near
/// the hero are loaded, and `world` keeps them loaded as the hero walks
/// (see [`Terrain::load_around`]). Everything else reads as solid forest.
#[derive(Resource, Debug, Clone)]
pub enum Terrain {
    /// A fixed valley walled in by forest.
    Valley(WorldMap),
    /// Endless ground streamed in chunks.
    Endless(ChunkedWorld),
}

impl Terrain {
    /// Chunks loaded on each side of the hero's chunk. One chunk is 32
    /// tiles, so everything within 32 tiles (512 units) of the hero, more
    /// than the creature leash, is always loaded.
    pub const LOADED_RADIUS: i32 = 1;
    /// Chunks kept before the least recently used are dropped: the 3x3
    /// around the hero plus room to walk back without regenerating.
    const CHUNK_CAPACITY: usize = 25;

    /// A fresh endless world for `seed`, already loaded around the start.
    pub fn endless(seed: u64) -> Self {
        let mut terrain = Self::Endless(ChunkedWorld::new(seed, Self::CHUNK_CAPACITY));
        let (x, y) = terrain.tiles().spawn_point();
        terrain.load_around(Vec2::new(x, y));
        terrain
    }

    /// The ground as collision, spawning, routing and drawing read it.
    pub fn tiles(&self) -> &dyn TileSource {
        match self {
            Self::Valley(map) => map,
            Self::Endless(world) => world,
        }
    }

    /// Whether the chunks around a world position are all loaded already.
    /// Always `true` for a valley.
    pub fn is_loaded_around(&self, position: Vec2) -> bool {
        let Self::Endless(world) = self else { return true };
        let (tx, ty) = WorldMap::tile_coords(position.x, position.y);
        let ((cx, cy), _) = chunk_coords(tx, ty);
        let r = Self::LOADED_RADIUS;
        (-r..=r).all(|dy| (-r..=r).all(|dx| world.is_loaded(cx + dx, cy + dy)))
    }

    /// Loads the chunks around a world position, dropping far ones once
    /// past capacity. Does nothing for a valley.
    pub fn load_around(&mut self, position: Vec2) {
        if let Self::Endless(world) = self {
            let (tx, ty) = WorldMap::tile_coords(position.x, position.y);
            world.load_around(tx, ty, Self::LOADED_RADIUS);
        }
    }
}

impl Default for Terrain {
    fn default() -> Self {
        Self::Valley(world::generate(16, 16, &mut GameRng::new(1)))
    }
}

/// Add trauma (`0..=1`) to shake the camera; `world` applies and decays it.
#[derive(Resource, Debug, Clone, Copy, Default)]
pub struct ScreenShake {
    pub trauma: f32,
}

impl ScreenShake {
    pub fn add(&mut self, trauma: f32) {
        self.trauma = (self.trauma + trauma).clamp(0.0, 1.0);
    }
}

/// The game's random number generator: the adapter behind the domain's
/// [`RandomSource`] port (xorshift64*).
#[derive(Resource, Debug, Clone)]
pub struct GameRng(u64);

impl GameRng {
    pub fn new(seed: u64) -> Self {
        // Scramble the seed (splitmix64) so nearby seeds diverge; never zero.
        let mut z = seed.wrapping_add(0x9E37_79B9_7F4A_7C15);
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        Self((z ^ (z >> 31)).max(1))
    }

    /// Next raw 64-bit value, e.g. to seed a world.
    pub fn next_u64(&mut self) -> u64 {
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }

    /// Random unit vector.
    pub fn direction(&mut self) -> Vec2 {
        Vec2::from_angle(self.range(0.0, std::f32::consts::TAU))
    }
}

impl Default for GameRng {
    fn default() -> Self {
        Self::new(0xE4BE_7B07)
    }
}

impl RandomSource for GameRng {
    fn next_f32(&mut self) -> f32 {
        (self.next_u64() >> 40) as f32 / (1u64 << 24) as f32
    }
}

pub(crate) fn register(app: &mut App) {
    app.init_resource::<PlayerIntent>()
        .init_resource::<HeroState>()
        .init_resource::<RunStats>()
        .init_resource::<BestRunRecord>()
        .init_resource::<BoonOffer>()
        .init_resource::<Terrain>()
        .init_resource::<ScreenShake>()
        .init_resource::<GameRng>();
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rng_is_uniform_enough_and_in_range() {
        let mut rng = GameRng::new(123);
        let samples: Vec<f32> = (0..10_000).map(|_| rng.next_f32()).collect();
        assert!(samples.iter().all(|v| (0.0..1.0).contains(v)));
        let mean = samples.iter().sum::<f32>() / samples.len() as f32;
        assert!((mean - 0.5).abs() < 0.02, "mean was {mean}");
    }

    #[test]
    fn an_endless_terrain_starts_loaded_and_follows_the_hero() {
        let mut terrain = Terrain::endless(5);
        let (x, y) = terrain.tiles().spawn_point();
        assert!(terrain.is_loaded_around(Vec2::new(x, y)));
        assert!(terrain.tiles().is_walkable_at(x, y, 6.0));
        let far = Vec2::new(40_000.0, -25_000.0);
        assert!(!terrain.is_loaded_around(far));
        terrain.load_around(far);
        assert!(terrain.is_loaded_around(far));
        // Everything within 32 tiles of the hero is loaded ground.
        for (dx, dy) in [(-511.0, 0.0), (511.0, 511.0), (0.0, -511.0)] {
            let Terrain::Endless(world) = &terrain else { unreachable!() };
            let (tx, ty) = WorldMap::tile_coords(far.x + dx, far.y + dy);
            assert!(world.loaded_tile(tx, ty).is_some(), "({dx}, {dy}) from the hero is not loaded");
        }
    }
}
